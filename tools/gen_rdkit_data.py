"""Generate src/chem/rdkitdata.nim: values RDKit's descriptors and
fingerprints are built on, so ours can match them exactly. Run with RDKit
installed: python tools/gen_rdkit_data.py

  * RDKit's atomic weights (its periodic table, older than the IUPAC values
    in `elements`);
  * the Rb0 radii Labute's approximate surface area uses;
  * the Wildman-Crippen atom types (Crippen.txt), in the order RDKit's C++
    code tries them: the pattern-type order of rdkit.Chem.Crippen, except
    that the H rows for H on N ('[#1][#7]') and on the O of an N-oxide/
    hydroxylamine ('[#1]O[#7]') come before the other H rows. With that
    order the first pattern that matches an atom gives RDKit's MolLogP and
    MolMR on every NCI test molecule.
"""
import os
from rdkit import Chem
from rdkit.Chem import Crippen

pt = Chem.GetPeriodicTable()
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def floats(values, per_line=6):
    lines = []
    for k in range(0, len(values), per_line):
        lines.append("  " + ", ".join(repr(float(v)) for v in values[k:k + per_line]) + ",")
    return "\n".join(lines)


# the type labels (C1, H1, ...) from the file, by SMARTS
labels = {}
for line in open(Crippen.defaultPatternFileName):
    if line.strip() and not line.startswith("#"):
        label, sma = line.split("\t")[:2]
        assert labels.setdefault(sma, label) == label, sma
Crippen._Init()
rows = []
for group in Crippen._patternOrder:
    rows += [(labels[r[0]],) + r for r in Crippen._smartsPatterns[group]]
h3 = [r for r in rows if r[1] in ("[#1][#7]", "[#1]O[#7]")]
assert len(h3) == 2
first_h = next(i for i, r in enumerate(rows) if r[1].startswith("[#1]"))
rest = [r for r in rows if r not in h3]
rows = rest[:first_h] + h3 + rest[first_h:]

crippen = "\n".join(f"  ({kind!r}, {sma!r}, {lp!r}, {mr!r}),".replace("'", '"')
                    for kind, sma, _, lp, mr in rows)
with open(os.path.join(root, "src", "chem", "rdkitdata.nim"), "w") as f:
    f.write(f"""## Data RDKit's descriptors and fingerprints are built on, so ours can
## match them exactly. Generated by tools/gen_rdkit_data.py from RDKit's
## periodic table and Crippen.txt; don't edit by hand.

# RDKit's average atomic weights (older than ours in `elements`, e.g.
# S 32.067)
const rdkitAtomicWeights*: array[0..118, float] = [
{floats([pt.GetAtomicWeight(z) for z in range(119)])}
]

# the radii Labute's approximate surface area uses (RDKit's Rb0)
const rb0Radii*: array[0..118, float] = [
{floats([pt.GetRb0(z) for z in range(119)])}
]

# Wildman-Crippen atom types, in the order RDKit tries them: each atom
# takes the first that matches it (as the pattern's first atom); atoms no
# type matches contribute 0
const crippenTypes*: array[{len(rows)}, tuple[label, smarts: string; logP, mr: float]] = [
{crippen}
]
""")
print(len(rows), "Crippen types written")
