"""Generate src/chem/isotopes.nim: exact isotope masses from RDKit's periodic
table (its atomic_data, from the AME/NIST evaluations). Run with RDKit
installed: python tools/gen_isotopes.py
"""
import os
from rdkit import Chem

pt = Chem.GetPeriodicTable()
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = []
for z in range(119):
    masses = [(a, pt.GetMassForIsotope(z, a)) for a in range(1, 400)] if z else []
    masses = [(a, m) for a, m in masses if m > 0]
    if masses:
        first = masses[0][0]
        assert [a for a, _ in masses] == list(range(first, first + len(masses))), z
        rows.append(f"  ({first}, @[{', '.join(repr(m) for _, m in masses)}]),  # {pt.GetElementSymbol(z)}")
    else:
        rows.append(f"  (0, @[]),  # {'*' if z == 0 else pt.GetElementSymbol(z)}")
with open(os.path.join(root, "src", "chem", "isotopes.nim"), "w") as f:
    f.write("""## Exact isotope masses, per element: the first mass number listed and the
## masses from there on. Generated by tools/gen_isotopes.py from RDKit's
## periodic table data (AME/NIST evaluations); don't edit by hand.

const isotopeMasses*: array[0..118, tuple[first: int, masses: seq[float]]] = [
""" + "\n".join(rows) + "\n]\n")
print(sum(1 for r in rows), "elements written")
